def check_dependencies():
    """
    Checks if all required and optional Python dependencies are installed.
    Exits the script if any critical dependency is missing.
    """
    print("=" * 60)
    print("Checking dependencies...")
    print("=" * 60)

    missing_critical = []
    missing_optional = []

    for import_name, pip_name, critical in REQUIRED:
        try:
            importlib.import_module(import_name)
            print(f"  ✓  {pip_name}")
        except ImportError:
            if critical:
                print(f"  ✗  {pip_name}  ← MISSING (required)")
                missing_critical.append(pip_name)
            else:
                print(f"  ⚠  {pip_name}  ← missing (optional)")
                missing_optional.append(pip_name)

    if missing_optional:
        print(f"\nOptional packages missing (some features disabled):")
        print(f"  pip install {' '.join(missing_optional)}")

    if missing_critical:
        print(f"\n❌ Install missing required packages:")
        print(f"  pip install {' '.join(missing_critical)}")
        sys.exit(1)

    print("\n✓ All required dependencies present.\n")


def clean_build():
    """
    Removes previous build artifacts such as the 'build' and 'dist' directories,
    '__pycache__', and any old PyInstaller .spec files to ensure a clean build.
    """
    print("=" * 60)
    print("Cleaning previous build artifacts...")
    print("=" * 60)

    folders = ["build", "dist", "__pycache__"]
    for folder in folders:
        if os.path.exists(folder):
            shutil.rmtree(folder)
            print(f"  Removed {folder}/")

    # Remove .spec generated ones (keep our custom one)
    for f in os.listdir("."):
        if f.endswith(".spec") and f != "glassnote.spec":
            os.remove(f)
            print(f"  Removed {f}")

    print()


